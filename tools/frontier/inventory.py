def git_master(path):
    r = subprocess.run(["git", "show", f"master:{path}"], capture_output=True, cwd=ROOT)
    return r.stdout.decode("utf-8", "replace").replace("\r\n", "\n")


def master_tmp(path, tmpdir):
    p = Path(tmpdir) / Path(path).name
    p.write_text(git_master(path), encoding="utf-8")
    return p


def vanilla_species_info():
    """master species -> dict(types, stats, abilities) from the vanilla species_info files"""
    out = {}
    for n in range(1, 10):
        t = git_master(f"src/data/pokemon/species_info/gen_{n}_families.h")
        parts = re.split(r"\n    \[(SPECIES_\w+)\] =\n", t)
        for i in range(1, len(parts), 2):
            b = parts[i + 1]
            ty = re.search(r"\.types = MON_TYPES\((\w+)(?:, (\w+))?\)", b)
            ab = re.search(r"\.abilities = \{ ([^}]*)\}", b)
            if not ty:
                continue
            st = {}
            for k, f in dict(hp="baseHP", atk="baseAttack", def_="baseDefense", spe="baseSpeed", spa="baseSpAttack", spd="baseSpDefense").items():
                m = re.search(r"\." + f + r"\s*=\s*(\d+)", b)
                st[k] = int(m.group(1)) if m else None
            out[parts[i]] = dict(types=[ty.group(1), ty.group(2) or ty.group(1)] if ty.group(2) else [ty.group(1)], stats=st,
                                 abilities=[x.strip() for x in ab.group(1).split(",")] if ab else [])
    return out


def vanilla_brains():
    t = git_master("src/frontier_util.c")
    i = t.index("sFrontierBrainsMons[][2][FRONTIER_PARTY_SIZE]")
    seg = t[i:t.index("\n};\n", i)]
    out = []
    for fm in re.finditer(r"\[(FRONTIER_FACILITY_\w+)\] =\n    \{(.*?)\n    \},", seg, flags=re.S):
        sym = 0
        for sb in re.split(r"// (?:Silver|Gold) Symbol\.", fm.group(2))[1:]:
            for mb in re.finditer(r"\.species = (\w+),\s*\.heldItem = (\w+),.*?\.nature = (\w+),\s*\.evs = \{([^}]*)\},\s*\.moves = \{([^}]*)\}", sb, flags=re.S):
                out.append(dict(facility=fm.group(1), symbol="silver" if sym == 0 else "gold", species=mb.group(1), item=mb.group(2),
                                nature=mb.group(3), ev=mb.group(4), moves=[x.strip() for x in mb.group(5).split(",")]))
            sym += 1
    return out


def wild_species(path):
    t = git_master(path)
    return re.findall(r"\.species = (SPECIES_\w+)", t)


def obtainable_items():
    toks = collections.Counter()
    for f in glob.glob(str(ROOT / "data/maps/*/scripts.inc")) + glob.glob(str(ROOT / "data/maps/*/map.json")) + glob.glob(str(ROOT / "data/scripts/*.inc")):
        # the Hoenn leftovers are not reachable: skip maps of the shut Frontier facilities except the Arena + lobby clerks
        try:
            t = open(f, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        for m in re.findall(r"ITEM_[A-Z0-9_]+", t):
            toks[m] += 1
    return toks


