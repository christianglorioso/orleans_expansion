"""Crescent City's floodwater state (fix B, ch6_2 S3): the levee road south of the city is under water until badge 6.

The map.bin holds the dry lawn and road. CrescentCity_OnLoad runs `CrescentCity_EventScript_StateFlooded` (generated by build.py from the spec's
"states") while FLAG_BADGE06_GET is clear: it setmetatile's the Johto-water pieces over the bottom three rows of the Route 14 connection
(x 39-66). The water's corner cells are rows 64-65 (the grid clamps beyond the map edge, so it runs on into Route 14's seam), so row 63 holds
the bank pieces (walkable shore: the trigger row turns the player back there) and rows 64-65 are water with collision 1 (nobody crosses, not even
a surfer: setmetatile keeps the layout's elevation 3). The corners use the same dual-grid rule as build.py's corners(), so every edge piece is
the right one. After badge 6 the load leaves the dry road in place.
"""
X0, X1 = 39, 66          # the Route 14 connection (28 wide); the water covers all of it, its banks are the cells at x 38 and 66
ROWS = (63, 64, 65)
CORNER_KEYS = {"1111": "C", "0011": "N", "1100": "S", "0101": "W", "1010": "E", "0111": "inNW", "1011": "inNE", "1101": "inSW", "1110": "inSE",
               "0001": "landSE", "0010": "landSW", "0100": "landNE", "1000": "landNW", "0110": "sTLBR", "1001": "sTRBL"}


def water_corner(x, y):
    """corner cells that are water: rows 64 and 65 (and beyond), x 39..66, so no dry column is left inside the connection"""
    return 64 <= y and X0 <= x <= X1


def cells():
    out = []
    for y in ROWS:
        for x in range(X0 - 1, X1 + 1):
            bits = "".join("1" if water_corner(x + dx, min(y + dy, 65)) else "0" for dx, dy in ((0, 0), (1, 0), (0, 1), (1, 1)))
            if bits == "0000":
                continue
            n = bits.count("1")
            out.append({"x": x, "y": y, "tile": "ekat:water_" + CORNER_KEYS[bits], "collision": 1 if (n >= 2 and y >= 64) else 0})
    return out


STATES = {"Flooded": cells()}
