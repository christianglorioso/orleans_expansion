"""Write the `// gTileset_General` block of include/constants/metatile_labels.h for the Orleans primary.

usage (from the decomp root):  python tools/mapgen/gen_metatile_labels.py

Emerald's engine code names primary metatiles of gTileset_General (METATILE_General_*: cut grass, secret bases, muddy slopes,
doors, sand pits ...). Orleans maps use gTileset_OrleansGeneral, whose ids are not Emerald's, so those labels pointed at
unrelated pieces (or collided with Orleans secondary ids). This script keeps every label name (the C and the scripts still
compile) and points each at the right Orleans piece where Orleans has one, read from tilesets/orleans_general.mapping.json:

    Grass / TallGrass / TallGrass_Marsh / Marsh / CalmWater      ekat:grass, ekat:tallgrass, patch:tallgrass_marsh, ekat:marsh_C, ekat:water_C
    everything else (secret base trees and caves, muddy slope,   an id nothing can read back (0x0F00 + n: a metatile id is 10
    sand pit, rough water, doors, long grass, tree grass ...)    bits, so MapGridGetMetatileIdAt never returns it): the
                                                                 feature is unused in Orleans, the code path just never matches

Run it after every compose of the primary (build.py never reads the header; only the C does).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
HEADER = os.path.join(ROOT, "include", "constants", "metatile_labels.h")
BEGIN, END = "// gTileset_General", "// gTileset_GenericBuilding\n"

REAL = {
    "Grass": "ekat:grass",
    "TallGrass": "ekat:tallgrass",
    "TallGrass_Marsh": "patch:tallgrass_marsh",   # new label: tall grass on a marsh patch
    "Marsh": "ekat:marsh_C",                       # new label: what cutting tall grass on marsh leaves
    "CalmWater": "ekat:water_C",
}
# labels of the original block, in order (the generated block keeps all of them)
ORIGINAL = """BlueCaveIndent BlueCaveOpen CalmWater CaveEntrance_Bottom CaveEntrance_Top Door Door_Contest Door_Gym Door_PokeCenter
Door_PokeMart Grass Grass_TreeLeft Grass_TreeRight Grass_TreeUp LongGrass MuddySlope_Frame0 MuddySlope_Frame1 MuddySlope_Frame2
MuddySlope_Frame3 RedCaveIndent RedCaveOpen ReflectiveWater RockWall_GrassBase RockWall_RockBase RockWall_SandBase RoughDeepWater
RoughWater SandPit_Center SecretBase_TreeLeft SecretBase_TreeRight SecretBase_VineLeft SecretBase_VineRight TallGrass
TallGrass_TreeLeft TallGrass_TreeRight TallGrass_TreeUp YellowCaveIndent YellowCaveOpen""".split()


def main():
    mapping = json.load(open(os.path.join(HERE, "tilesets", "orleans_general.mapping.json")))["metatiles"]
    names = sorted(set(ORIGINAL) | set(REAL))
    lines, dummy = [], 0
    for n in names:
        if n in REAL:
            if REAL[n] not in mapping:
                raise SystemExit(f"the primary has no {REAL[n]} (needed for METATILE_General_{n})")
            v = mapping[REAL[n]]
            note = f"   // {REAL[n]}"
        else:
            v = 0x0F00 + dummy
            dummy += 1
            note = "   // unused in Orleans (no such piece in gTileset_OrleansGeneral; never matches)"
        lines.append(f"#define METATILE_General_{n:<26} 0x{v:03X}{note}\n")
    block = ("// gTileset_OrleansGeneral (the Orleans primary; the label names are Emerald's gTileset_General ones)\n"
             "// GENERATED by tools/mapgen/gen_metatile_labels.py from tilesets/orleans_general.mapping.json: do not edit by hand.\n"
             + "".join(lines) + "\n")
    src = open(HEADER, encoding="utf-8").read()
    # the block starts at either heading (first run: Emerald's, later runs: ours) and ends before gTileset_GenericBuilding
    m = re.search(r"// gTileset_(?:General|OrleansGeneral)[^\n]*\n", src)
    e = src.index(END)
    new = src[:m.start()] + block + src[e:]
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print(f"wrote {len(lines)} labels ({len(REAL)} real, {dummy} unused) into {os.path.relpath(HEADER, ROOT)}")


if __name__ == "__main__":
    main()
