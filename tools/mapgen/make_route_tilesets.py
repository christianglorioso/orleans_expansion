"""Route tileset variants: copies of the route set (tilesets/orleans_route.json + recipes/orleans_route.json) under
their own name, for routes that need room the shared set hasn't got. Each is demand-driven like the original
(compose keeps only what its maps place), so a variant costs only what its own routes use.

    orleans_river   routes along river channels: their levee pieces (levee.py) would overflow the shared set
    orleans_route_b Route 14 and the Oldest Shrine (the later routes before the Gulf and dry-country splits)
    orleans_coast   Route 2 alone: the power line (towers, wire spans), the lookout, the beach and the fallen cables
    orleans_gulf    Gulf Routes 18, 19, 20: bird platform, shipwreck, oyster beds, pilings and buoys of the landmark art
    orleans_offshore Routes 21, 22, 25: the offshore platform, the temple gate, the shrine steps (landmark art)
    orleans_route_dry  Routes 23, 24 and orleans_route_farm Routes 15, 16, 17: the route set plus the dry-country art (dry_route_tileset.py)

usage (from the decomp root): python tools/mapgen/make_route_tilesets.py   (then compose --register)
Which routes use which variant: town_plans.TOWN_CFG. Edit orleans_route's files, then rerun this.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TS = os.path.join(HERE, "tilesets")
VARIANTS = {"orleans_river": {"symbol": "gTileset_OrleansRiver",
                              "what": "routes along river channels (the levee pieces)"},
            "orleans_route_b": {"symbol": "gTileset_OrleansRouteB",
                                "what": "Route 14 and the Oldest Shrine (the later routes' set; the Gulf and dry routes split off)"},
            "orleans_coast": {"symbol": "gTileset_OrleansCoast",
                              "what": "Route 2, the coast: its power line, wires, lookout and beach (landmark art, 174+ tiles)"},
            "orleans_gulf": {"symbol": "gTileset_OrleansGulf",
                             "what": "the Gulf routes 18, 19, 20: the landmark art's bird platform, wrecks, oyster beds and pilings"},
            "orleans_offshore": {"symbol": "gTileset_OrleansOffshore",
                                 "what": "Routes 21, 22, 25: the offshore platform, the temple gate and the shrine steps (landmark art)"},
            "orleans_route_dry": {"symbol": "gTileset_OrleansRouteDry", "addon": "dry_route_tileset",
                                  "what": "the dry country (Routes 17, 23, 24): the dry-country art set"},
            "orleans_route_farm": {"symbol": "gTileset_OrleansRouteFarm", "addon": "dry_route_tileset",
                                   "what": "the farm routes (15 the cane fields, 16 the pepper fields, 17 the sugar mill road): cane wall, red earth, pepper, mills"}}


def camel(name):
    return "".join(p.title() for p in name.split("_"))


def make(name):
    v = VARIANTS[name]
    c = json.load(open(os.path.join(TS, "orleans_route.json"), encoding="utf-8"))
    r = json.load(open(os.path.join(TS, "recipes", "orleans_route.json"), encoding="utf-8"))
    c["_comment"] = f"{name}: the route set for {v['what']}; generated by make_route_tilesets.py from orleans_route."
    c["secondary"], c["secondary_dir"] = v["symbol"], f"data/tilesets/secondary/{name}"
    c["mappings"] = ["orleans_general.mapping.json", f"{name}.mapping.json"]
    c["blends_file"] = f"{name}.blends.json"
    r["_comment"] = f"{name}: generated by make_route_tilesets.py from recipes/orleans_route.json. " + r["_comment"]
    r["dir"], r["symbol"], r["blends_file"] = name, v["symbol"], f"{name}.blends.json"
    r["demand"] = True
    if os.environ.get("BOOT") == name:  # first compose of a new variant: no map uses it yet, so compose keeps everything: leave the
        # landmark art out (it would not fit), build once so its layouts write their uses files, then regenerate without BOOT
        r["sources"] = [x for x in r["sources"] if x["name"] != "lmk"]
        c["prefabs"] = {k: v for k, v in c["prefabs"].items() if not v.get("_lmk")}
    if v.get("addon"):  # the variant's own art on top of the copy (e.g. dry_route_tileset for the dry country)
        import sys
        sys.path.insert(0, HERE)
        __import__(v["addon"]).apply(r, c)
    for path, obj in ((os.path.join(TS, f"{name}.json"), c), (os.path.join(TS, "recipes", f"{name}.json"), r)):
        with open(path + ".new", "w", encoding="utf-8", newline="\n") as f:
            json.dump(obj, f, indent=1, ensure_ascii=False)
            f.write("\n")
        os.replace(path + ".new", path)
    print(name, "->", v["symbol"])


def patch_base():
    """The landmark art goes onto the shared route set itself (in place, idempotent), then every variant copies it."""
    import sys
    sys.path.insert(0, HERE)
    import landmarks_tileset
    cp, rp = os.path.join(TS, "orleans_route.json"), os.path.join(TS, "recipes", "orleans_route.json")
    c, r = json.load(open(cp, encoding="utf-8")), json.load(open(rp, encoding="utf-8"))
    if landmarks_tileset.apply(r, c):
        for path, obj in ((cp, c), (rp, r)):
            with open(path + ".new", "w", encoding="utf-8", newline="\n") as f:
                json.dump(obj, f, indent=1, ensure_ascii=False)
                f.write("\n")
            os.replace(path + ".new", path)
        print("orleans_route: route landmarks art applied")


if __name__ == "__main__":
    patch_base()
    for n in VARIANTS:
        make(n)
