def art_doc():
    t, ents = ppdata.load()
    out = ["# Commissioned art pending", "",
           "Every species below is wired to PLACEHOLDER graphics (the base species' assets) until the commissioned art arrives.",
           "Replace the listed symbols' source files (graphics/pokemon/<species>/...) or point the species block at new symbols.",
           "Species blocks: src/data/pokemon/species_info/orleans_forms.h (regional forms) and orleans_megas.h (custom Megas).", ""]

    def assets(const):
        b = ents[const]
        g = lambda f: (re.search(r"\." + f + r" = (\w+)", b) or [None, "-"])[1]
        fp = re.search(r"\.footprint = (\w+)", b)
        ow = re.search(r"\.images = (\w+)", b)
        return (f"front `{g('frontPic')}`, back `{g('backPic')}`, palette `{g('palette')}`, shiny `{g('shinyPalette')}`, "
                f"icon `{g('iconSprite')}` (pal {g('iconPalIndex')}), footprint `{fp.group(1) if fp else '-'}`, "
                f"overworld `{ow.group(1) if ow else '-'}`")

    out += ["## Orleanian regional forms (22): no art yet, all assets are the base species'", "",
            "| Species | Form | Placeholder assets |", "|---|---|---|"]
    for n in sm.ORLEANIAN:
        c = sm.orleanian_const(n)
        out.append(f"| {n} | `{c}` | {assets(c)} |")
    out += ["", "## Custom Megas (16): new Mega art needed; placeholder = the base form's normal sprites", "",
            "| Mega | Species constant | Stone | Placeholder assets |", "|---|---|---|---|"]
    for name, (base, item, disp) in sm.CUSTOM_MEGA_BASE.items():
        c = sm.CUSTOM_MEGAS[name]
        out.append(f"| {name} | `{c}` | {disp} (`{item}`) | {assets(c)} (base `{base}`) |")
    out += ["", "## Items using placeholder icons", "",
            "- the 16 custom Mega stones use `gItemIcon_Lucarionite` / `gItemIconPalette_Lucarionite`",
            "- Fais Do-Do Ribbon (`ITEM_FAIS_DO_DO_RIBBON`) uses the Sun Stone icon", "",
            "## Other art notes", "",
            "- The regional Pokedex still shows the HOENN title graphic on its first page (pokedex background tiles); the text modes say ORLEANS.",
            "- Descriptions (Pokedex text) of the Orleanian forms are the base species' text; rewrite them with the art.",
            "- ART REQUEST (not drawn): the HOENN label sprite on the regional Pokedex list header (graphics/pokedex/interface.png, `sSpriteAnim_HoennText` in src/pokedex.c) should read ORLEANS.",
            "- ART REQUEST (not drawn): the PokeNav header `gPokenavLeftHeaderHoennMap_Gfx` and the Pokedex region-map graphics (graphics/pokedex/region_map.png, Hoenn terrain) need Orleans versions; the Area page shows no glow for Orleans map sections until then.",
            "- ART REQUEST (not drawn): the Pokedex background/search-menu files are still named bg_hoenn / search_menu_hoenn; recolour/rename only if the artist redoes the screen.", ""]
    (HERE / "commissioned_art_pending.md").write_text("\n".join(out), encoding="utf-8")
    return len(sm.ORLEANIAN) + len(sm.CUSTOM_MEGA_BASE)


def tm_doc():
    plan = json.loads((HERE / "out/tm_plan.json").read_text(encoding="utf-8"))
    tms, hms, overflow, counts = plan["tms"], plan["hms"], plan["overflow"], plan["counts"]
    h, rows = sd.load_move_index()
    mt = {sd.norm(r[0]): r for r in rows if r[0]}
    mv = sd.load_move_names()
    inv = {v: k for k, v in mv.items()}

    def info(m):
        r = mt.get(inv.get(m, ""))
        if not r:
            return ("?", "?", "?")
        return (r[1], r[2], r[3] if isinstance(r[3], (int, float)) else "-")

    gyms = {  # fixed story rewards + proposals for the unassigned leaders (all are TM-list moves)
        "MOVE_TRAILBLAZE": "Gym 1 reward (Magnolia) - DECIDED",
        "MOVE_SHOCK_WAVE": "Gym 2 reward (Eclair) - DECIDED",
        "MOVE_SHADOW_BALL": "Gym 3 reward (Fifolet) - DECIDED",
        "MOVE_AERIAL_ACE": "Gym 4 reward (Kingfisher) - proposed",
        "MOVE_SLUDGE_BOMB": "Gym 5 reward (Boudreaux and Thibodeaux) - proposed",
        "MOVE_DAZZLING_GLEAM": "Gym 6 reward (Lutin) - proposed",
        "MOVE_OVERHEAT": "Gym 7 reward (Cayenne) - proposed",
        "MOVE_SCALD": "Gym 8 reward (Heron) - proposed",
    }
    lines = ["# Orleans TM list (planning doc)", "",
             f"{len(tms)} TMs (TM001-TM{len(tms)}), generated by tools/dex/apply_learnsets.py from orleans_learnsets.xlsx.",
             "The first 51 are the original list (Hoenn TM01-TM50 order, then Trailblaze as TM051); TM052 onward are the next most widely",
             "learnable moves in the sheet (by number of dex species that learn them by TM or tutor).", "",
             "## Limits found (why not 489)",
             "- Item ids are a 10-bit field (held items, bag, party): ITEMS_COUNT must stay below 1024. ITEMS_COUNT is 916, so 107 ids remain for story items (1023 - 916).",
             "  Each extra TM costs one id, so the TM list is capped at 122 (it was 100 slots, 51 filled).",
             "- SaveBlock1 has 40 spare bytes after sizing the TM pocket (BAG_TMHM_COUNT = 130 = 122 TMs + 8 HMs, 4 bytes a slot). More TMs would not fit the save.",
             "- Every other move the sheet teaches by TM or tutor is taught through the Move Relearner's tutor list (src/data/pokemon/special_movesets.json",
             f"  `extraTutors`, {len(overflow)} moves). P_FLAG_TUTOR_MOVES = FLAG_ORLEANS_TUTOR_RELEARNER, which the Crescent City tutor (services house) sets on first talk;",
             "  the tutor's new 'OTHER MOVES' choice opens the relearner's tutor list for any party Pokemon (free). Dedicated tutor NPCs would just set the same flag.",
             "- HMs: the 8 Hoenn HMs (Cut, Fly, Surf, Strength, Flash, Rock Smash, Waterfall, Dive) are unchanged. No HM was added. They are only a learnset category now;",
             "  the field effects are key items (Garden Shears, Pry Bar, ...), Surf stays a move.", "",
             "## TM numbers", "", "| TM | Move | Type | Cat | Power | Species | Suggested source |", "|---|---|---|---|---|---|---|"]
    mart_order = []
    for i, m in enumerate(tms, 1):
        ty, cat, pw = info(m)
        c = counts.get(m, 0)
        if m in gyms:
            src = gyms[m]
        elif i <= 51 and m not in gyms:
            src = "mart / item ball (original Hoenn TM; keep its story placement if any)"
        else:
            if c >= 200:
                src = "mart from the start (very common support/utility move)"
            elif isinstance(pw, (int, float)) and pw >= 100:
                src = "mart after badge 6, or a post-game item ball"
            elif isinstance(pw, (int, float)) and pw >= 80:
                src = "mart after badge 4, or an item ball on Routes 7-12"
            elif cat == "Status":
                src = "item ball (Routes 3-9)" if c >= 40 else "mart after badge 3"
            else:
                src = "mart after badge 2, or an item ball on Routes 1-6"
        lines.append(f"| TM{i:03d} | {m[5:].replace('_', ' ').title()} | {ty} | {cat} | {pw} | {c} | {src} |")
    lines += ["", "## HMs (unchanged)", ""] + [f"- HM{i:02d} {m[5:].replace('_', ' ').title()}" for i, m in enumerate(hms, 1)]
    lines += ["", f"## Tutor (Move Relearner) moves added for the sheet: {len(overflow)}", "",
              "The original Hoenn script tutors (Swagger, Rollout, ...) keep working. These moves are also offered by the relearner tutor list:", ""]
    lines.append(", ".join(m[5:].replace("_", " ").title() for m in overflow))
    (HERE / "tm_list.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(tms)


if __name__ == "__main__":
    print("art entries:", art_doc(), "tms:", tm_doc())


