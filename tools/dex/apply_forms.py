"""Stage 2: the 22 Orleanian regional-form species (clones of the base species with placeholder graphics).

Each new species SPECIES_<X>_ORLEANIAN is a copy of the base species block (same sprites/icon/footprint/cry/natDexNum)
with the sheet's types/stats/abilities, evolutions pointing at the Orleanian chain, and a form table listing it first.
Idempotent: regenerates src/data/pokemon/species_info/orleans_forms.h and patches tables only if needed.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import apply_stats
import cdata
import orleans_gen as g
import sheet_data
import species_map as sm

OUT = Path(__file__).resolve().parent / "out"
EVO_OVERRIDE = {
    "Koffing": "EVOLUTION({EVO_LEVEL, 35, SPECIES_WEEZING_ORLEANIAN})",
    "Exeggcute": "EVOLUTION({EVO_ITEM, ITEM_LEAF_STONE, SPECIES_EXEGGUTOR_ORLEANIAN})",
}


def main():
    g.ensure_species_consts()
    sf = cdata.SpeciesFiles()
    dex = {r["name"]: r for r in sheet_data.load_dex() if r["kind"] == "species"}
    ftxt = g.FORM_SPECIES_H.read_text(encoding="utf-8")
    new_tables = ""
    blocks = []
    pend = []  # placeholder records
    for name in sm.ORLEANIAN:
        base = sm.base_of_orleanian(name)
        new = sm.orleanian_const(name)
        row = dex[name]
        raw = sf.get(base)
        assert raw, base
        b = raw.replace(f"    [{base}] =", f"    [{new}] =", 1)
        wa = [sm.ability_const(a) for a in row["abilities"]]
        b, done = apply_stats.edit_region(b, row, wa, set(apply_stats.STATS) | {"types", "abilities"})
        assert len(done) == 8, (name, done)
        # evolutions -> Orleanian chain
        for other in sm.ORLEANIAN:
            ob = sm.base_of_orleanian(other)
            b = re.sub(r"(\bEVO_\w+,[^\n]*?)\b" + ob + r"\b(?!_)", lambda m: m.group(1) + sm.orleanian_const(other), b)
        if name in EVO_OVERRIDE:  # drop the Galar/Alola region branches
            b = g.set_or_insert_field(b, "evolutions", EVO_OVERRIDE[name], before=("formSpeciesIdTable",))
        # no inherited form-change table (Gmax / Mega belong to the base species); stage 3 adds Orleanian ones
        b = g.remove_field(b, "formChangeTable")
        # form table
        m = re.search(r"\.formSpeciesIdTable = (\w+)", b)
        if m:
            tname = m.group(1)
            ft = ftxt
            tm = re.search(r"static const u16 " + tname + r"\[\] = \{\n", ft)
            assert tm, tname
            if new not in ft[tm.end():tm.end() + 200]:
                ftxt = ft[:tm.end()] + f"    {new},\n" + ft[tm.end():]
        else:
            tname = g.table_name(base)
            new_tables += g.form_table_text(tname, [new, base])
            sf.put(base, g.set_or_insert_field(raw, "formSpeciesIdTable", tname))
            b = g.set_or_insert_field(b, "formSpeciesIdTable", tname)
        # the clone's header comment
        blocks.append(b)
        pend.append((new, base))
    g.FORM_SPECIES_H.write_text(ftxt, encoding="utf-8", newline="\n")
    if new_tables:
        g.append_to_text_file(g.FORM_SPECIES_H, "// Orleans regional-form tables", "// Orleans regional-form tables (tools/dex/apply_forms.py)\n" + new_tables)
    sf.save()
    hdr = ("// Orleanian regional forms: generated by tools/dex/apply_forms.py from orleans_dex.xlsx.\n"
           "// Graphics, cry, footprint and overworld sprites are PLACEHOLDERS (the base species' assets) until the\n"
           "// commissioned art arrives; see tools/dex/commissioned_art_pending.md.\n\n")
    g.ORL_FORMS_H.write_text(hdr + "\n".join(blocks), encoding="utf-8", newline="\n")
    g.include_in_species_info("orleans_forms.h")
    OUT.mkdir(exist_ok=True)
    (OUT / "forms_pending_art.txt").write_text("\n".join(f"{a}\t{b}" for a, b in pend), encoding="utf-8")
    print("forms:", len(blocks))


if __name__ == "__main__":
    main()
