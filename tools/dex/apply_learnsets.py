NUM_TMS = 122  # total TM001..TM122: item ids < 1024 (10-bit heldItem) and SaveBlock1 size (4 bytes per bag slot, 40 bytes spare); see tm_list.md


# --------------------------------------------------------------------------------------------- level-up / egg
def lv_text(name, moves):
    body = "".join(f"    LEVEL_UP_MOVE({lvl:2d}, {m}),\n" for lvl, m in moves)
    return f"static const struct LevelUpMove {name}[] = {{\n{body}    LEVEL_UP_END\n}};\n"


def egg_text(name, moves):
    body = "".join(f"    {m},\n" for m in moves)
    return f"static const u16 {name}[] = {{\n{body}    MOVE_UNAVAILABLE,\n}};\n"


def replace_array(text, decl_re, new):
    m = re.search(decl_re, text, re.S)
    if not m:
        return None
    return text[:m.start()] + new + text[m.end():]


def level_up_and_egg(rows, sf):
    lv = LV_H.read_text(encoding="utf-8")
    egg = EGG_H.read_text(encoding="utf-8")
    sig = collections.defaultdict(set)
    for r in rows:
        sig[r["ptr_lv"]].add(tuple(r["levelup"]))
    sigt = collections.defaultdict(set)
    for r in rows:
        sigt[r["ptr_tm"]].add(tuple(sorted(set(r["tm"]) | set(r["tutor"]))))
    done_lv, done_egg, done_tm = set(), set(), set()
    for r in rows:
        p = r["ptr_tm"]
        if not p or "None" in p:
            continue
        if len(sigt[p]) > 1 and p in done_tm:
            stem = r["const"][len("SPECIES_"):]
            newp = "s" + g.pascal("SPECIES_" + stem) + "TeachableLearnset"
            blk = sf.get(r["const"])
            sf.put(r["const"], re.sub(r"\.teachableLearnset = " + p, ".teachableLearnset = " + newp, blk))
            r["ptr_tm"] = newp
        done_tm.add(p)
    notes = []
    for r in rows:
        p = r["ptr_lv"]
        if p is None or "None" in p:
            notes.append(f"{r['name']}: no level-up array")
            continue
        if len(sig[p]) > 1 and p in done_lv:
            # conflicting sharer: give this species its own array
            stem = r["const"][len("SPECIES_"):]
            newp = "s" + g.pascal("SPECIES_" + stem) + "LevelUpLearnset"
            blk = sf.get(r["const"])
            assert blk, r["const"]
            sf.put(r["const"], re.sub(r"\.levelUpLearnset = " + p, ".levelUpLearnset = " + newp, blk))
            lv = lv.rstrip("\n") + "\n\n" + lv_text(newp, r["levelup"])
            done_lv.add(newp)
            r["ptr_lv"] = newp
            notes.append(f"{r['name']}: own level-up array {newp}")
            continue
        new = lv_text(p, r["levelup"])
        res = replace_array(lv, r"static const struct LevelUpMove " + p + r"\[\] = \{.*?\n\};\n", new)
        if res is None:  # array introduced by an earlier run's pointer rename but not yet defined
            res = lv.rstrip("\n") + "\n\n" + new
        lv = res
        done_lv.add(p)
    for r in rows:
        p = r["ptr_egg"]
        if not p or "None" in p or p in done_egg:
            continue
        done_egg.add(p)
        res = replace_array(egg, r"static const u16 " + p + r"\[\] = \{.*?\n\};\n", egg_text(p, r["egg"]))
        assert res is not None, p
        egg = res
    LV_H.write_text(lv, encoding="utf-8", newline="\n")
    EGG_H.write_text(egg, encoding="utf-8", newline="\n")
    return notes


# --------------------------------------------------------------------------------------------- TMs / tutors
def reflow(desc, width=20, lines=3):
    words = desc.split()
    out, cur = [], ""
    for w in words:
        if len(cur) + len(w) + (1 if cur else 0) <= width:
            cur = (cur + " " + w) if cur else w
        else:
            out.append(cur)
            cur = w
    out.append(cur)
    return out[:lines]


def move_descriptions():
    txt = (ROOT / "src/data/moves_info.h").read_text(encoding="utf-8")
    parts = re.split(r"\n    \[(MOVE_\w+)\] =", txt)
    out = {}
    for i in range(1, len(parts), 2):
        m = re.search(r"\.description = COMPOUND_STRING\(\s*((?:\"[^\"]*\"\s*)+)\)", parts[i + 1])
        if m:
            s = "".join(re.findall(r'"([^"]*)"', m.group(1)))
            out[parts[i]] = s.replace("\\n", " ")
    return out


def current_tm_lists():
    # the original 51 TMs / 8 HMs (pristine copy of the file as the expansion + Trailblaze had it)
    src = (Path(__file__).resolve().parent / "base_tms_hms.h").read_text(encoding="utf-8")
    tm_part = src.split("#define FOREACH_HM")[0]
    hm_part = src.split("#define FOREACH_HM")[1].split("#define FOREACH_TMHM")[0]
    tms = ["MOVE_" + x for x in re.findall(r"F\((\w+)\)", tm_part)]
    hms = ["MOVE_" + x for x in re.findall(r"F\((\w+)\)", hm_part)]
    return tms, hms


def script_tutors():
    """moves the unchanged Hoenn tutor scripts offer (what make_tutors.py finds)"""
    out = set()
    for p in list((ROOT / "data/scripts").glob("*.inc")) + list((ROOT / "data/maps").glob("*/scripts.inc")):
        t = p.read_text(encoding="utf-8", errors="ignore")
        out.update(re.findall(r"move_tutor (MOVE_[A-Z_0-9]+)", t))
        if "special ChooseMonForMoveTutor" in t or "chooseboxmon SELECT_PC_MON_MOVE_TUTOR" in t:
            out.update(re.findall(r"setvar VAR_0x8005, (MOVE_[A-Z_0-9]+)", t))
    return out


def plan_tms(rows):
    cnt = collections.Counter()
    for r in rows:
        for m in set(r["tm"]) | set(r["tutor"]):
            cnt[m] += 1
    old_tms, hms = current_tm_lists()
    tutors0 = script_tutors()
    rest = [m for m, c in sorted(cnt.items(), key=lambda x: (-x[1], x[0]))
            if m not in old_tms and m not in hms and m not in tutors0]
    new_tms = old_tms + rest[:NUM_TMS - len(old_tms)]
    overflow = sorted(m for m in cnt if m not in new_tms and m not in hms and m not in tutors0)
    return new_tms, hms, overflow, cnt, tutors0


def write_tms_hms(new_tms):
    src = TMS_HMS.read_text(encoding="utf-8")
    pre = src.split("#define FOREACH_TM(F)")[0]
    head, tail = src.split("#define FOREACH_HM")
    lines = []
    for m in new_tms:
        n = m[len("MOVE_"):]
        c = "  /* Orleans: Magnolia's TM */" if n == "TRAILBLAZE" else ""
        lines.append(f"    F({n}){c} {chr(92)}")
    body = "#define FOREACH_TM(F) " + chr(92) + "\n" + "\n".join(lines)
    body = body.rstrip(chr(92)).rstrip() + "\n\n"
    TMS_HMS.write_text(pre + body + "#define FOREACH_HM" + tail, encoding="utf-8", newline="\n")


def update_items(new_tms, hms):
    ct = ITEMS_C.read_text(encoding="utf-8")
    m1 = re.search(r"^    ITEM_TM01 = (\d+),$", ct, re.M)
    base = int(m1.group(1))
    m100 = re.search(r"^    ITEM_TM(\d+) = (\d+),$", ct[::1], re.M)
    tm_nums = [(int(a), int(b)) for a, b in re.findall(r"^    ITEM_TM(\d+) = (\d+),$", ct, re.M)]
    hm_nums = [(int(a), int(b)) for a, b in re.findall(r"^    ITEM_HM(\d+) = (\d+),$", ct, re.M)]
    old_n = len(tm_nums)
    old_end = hm_nums[-1][1]  # last HM id
    n = len(new_tms)
    if old_n == n:
        return n, 0
    delta = n - old_n
    lines = ct.split("\n")
    out = []
    for ln in lines:
        mm = re.match(r"^    ITEM_TM(\d+) = \d+,$", ln)
        if mm:
            continue
        mh = re.match(r"^    ITEM_HM(\d+) = (\d+),$", ln)
        if mh:
            out.append(f"    ITEM_HM{mh.group(1)} = {int(mh.group(2)) + delta},")
            continue
        mi = re.match(r"^(    ITEM_\w+ = )(\d+)(,.*)$", ln)
        if mi and int(mi.group(2)) > old_end:
            out.append(f"{mi.group(1)}{int(mi.group(2)) + delta}{mi.group(3)}")
            continue
        out.append(ln)
    # insert TM constants before ITEM_HM01
    idx = next(i for i, ln in enumerate(out) if ln.startswith("    ITEM_HM01 = "))
    tmlines = [f"    ITEM_TM{i:02d} = {base + i - 1}," if i < 100 else f"    ITEM_TM{i} = {base + i - 1}," for i in range(1, n + 1)]
    out[idx:idx] = tmlines
    ITEMS_C.write_text("\n".join(out), encoding="utf-8", newline="\n")
    return n, delta


def update_item_data(new_tms, descs):
    dt = ITEMS_D.read_text(encoding="utf-8")
    a = dt.index("    [ITEM_TM51] =") if "    [ITEM_TM51] =" in dt else dt.index("    [ITEM_TM_TRAILBLAZE] =")
    b = dt.index("    [ITEM_HM_CUT] =")
    blocks = []
    for i, mv in enumerate(new_tms, 1):
        if i <= 50:
            continue
        name = "TM%02d" % i if i < 100 else "TM%d" % i
        d = reflow(descs.get(mv, "?????"))
        desc = "\n".join(f'            "{l}{chr(92)}n"' if k < len(d) - 1 else f'            "{l}"' for k, l in enumerate(d))
        blocks.append(f'    [ITEM_TM_{mv[5:]}] =\n    {{\n        .name = ITEM_NAME("{name}"),\n        .price = 3000,\n'
                      f'        .description = COMPOUND_STRING(\n{desc}),\n        .importance = I_REUSABLE_TMS,\n'
                      f'        .pocket = POCKET_TM_HM,\n        .type = ITEM_USE_PARTY_MENU,\n'
                      f'        .fieldUseFunc = ItemUseOutOfBattle_TMHM,\n    }},\n')
    dt = dt[:a] + "\n".join(blocks) + "\n" + dt[b:]
    ITEMS_D.write_text(dt, encoding="utf-8", newline="\n")


def main():
    rows = lm.build()
    sf = cdata.SpeciesFiles()
    notes = level_up_and_egg(rows, sf)
    sf.save()
    new_tms, hms, overflow, cnt, tutors0 = plan_tms(rows)
    # all_learnables for the dex species
    data = json.loads(LEARNABLES.read_text(encoding="utf-8"))
    key_moves = {}
    for r in rows:
        p = r["ptr_tm"]
        if not p or "None" in p:
            continue
        key = lm.snake_key(p)
        key_moves[key] = sorted(set(r["tm"]) | set(r["tutor"]))
    for k, v in key_moves.items():
        data[k] = v
    LEARNABLES.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")
    sp = json.loads(SPECIAL.read_text(encoding="utf-8"))
    sp["universalMoves"] = []
    sp["extraTutors"] = overflow
    SPECIAL.write_text(json.dumps(sp, indent=2) + "\n", encoding="utf-8", newline="\n")
    write_tms_hms(new_tms)
    n, delta = update_items(new_tms, hms)
    update_item_data(new_tms, move_descriptions())
    gt = GLOBAL_H.read_text(encoding="utf-8")
    gt = re.sub(r"#define BAG_TMHM_COUNT \d+", f"#define BAG_TMHM_COUNT {n + len(hms)}", gt)
    GLOBAL_H.write_text(gt, encoding="utf-8", newline="\n")
    mx = max(len(set(r["tm"]) | set(r["tutor"])) for r in rows)
    rt = RELEARNER_H.read_text(encoding="utf-8")
    rt = re.sub(r"#define MAX_RELEARNER_MOVES \d+", f"#define MAX_RELEARNER_MOVES {max(60, mx + len(tutors0) + 16)}", rt)
    RELEARNER_H.write_text(rt, encoding="utf-8", newline="\n")
    OUT.mkdir(exist_ok=True)
    (OUT / "stage5_notes.md").write_text(
        "\n".join(["# stage 5", f"TMs: {n} (id shift {delta})", f"overflow tutors: {len(overflow)}", f"script tutors kept: {sorted(tutors0)}", ""] + notes),
        encoding="utf-8")
    json.dump(dict(tms=new_tms, hms=hms, overflow=overflow, counts=cnt), open(OUT / "tm_plan.json", "w"), indent=1)
    print("TMs", n, "overflow tutors", len(overflow), "max teachable per species", mx)


if __name__ == "__main__":
    main()
