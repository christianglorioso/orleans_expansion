"""Stage 5: learnsets and TMs from orleans_learnsets.xlsx.

* level-up learnsets (src/data/pokemon/level_up_learnsets/gen_9.h, the one P_LVL_UP_LEARNSETS=GEN_LATEST uses)
* egg move arrays (src/data/pokemon/egg_moves.h) for the species that own one
* TM/tutor compatibility, through the expansion's own learnset helper: src/data/pokemon/all_learnables.json (per species:
  the sheet's TM + tutor moves), special_movesets.json (no universal moves; overflow moves become extraTutors),
  include/constants/tms_hms.h (the Orleans TM list) -> teachable_learnsets.h is generated by the build
* TM items: constants (include/constants/items.h), item data (src/data/items.h), BAG_TMHM_COUNT
* tools/dex/tm_list.md (planning doc)
Idempotent.
"""
